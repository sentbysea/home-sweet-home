const ell = (part, tone, x, y, rx, ry, rot = 0) => ({ t: 'ell', part, tone, x, y, rx, ry, rot });
const cap = (part, tone, a, b, r, r2 = r) => ({ t: 'cap', part, tone, a, b, r, r2 });
const path = (part, tone, pts, r, r2 = r) => ({ t: 'path', part, tone, pts, r, r2 });
const poly = (part, tone, pts) => ({ t: 'poly', part, tone, pts });
const cut = (prim) => ({ ...prim, cut: true });

