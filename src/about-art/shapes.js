//   좌표: 세로 0(위) ~ 100(바닥), 가로는 0 이 가운데. 화면에서는 네 형상 모두 아트 칸 한가운데에 같은 틀로 놓인다
//   (형상 높이에 맞추되 넓이가 모자라면 span 으로 줄인다 — about-art/index.js rasterize).
//   도형(prims) — 뒤에 적은 것이 앞을 덮는다. cut 이면 그 자리를 비운다.
//     ell  { x, y, rx, ry, rot }       타원(rot 도)
//     cap  { a:[x,y], b:[x,y], r, r2 } 두 점을 잇는 둥근 막대(r → r2 로 가늘어진다)
//     path { pts:[[x,y]…], r, r2 }     cap 을 이어 붙인 굽은 막대
//     poly { pts:[[x,y]…] }            다각형
//   tone — 0(옅은 글자) ~ 1(진한 글자). 칸의 바깥 테두리는 저절로 진해진다(윤곽).
//   parts — 부분마다 색(ink) · 모이는 차례(order: 0~1 의 시작 · 끝, sweep: 그 안에서 up · down · out · left · right) ·
//     완성 뒤 흔들림(sway: amp 단위만큼, from → to 로 갈수록 크게).
//   fx — 완성 뒤 한 번 · 계속 움직이는 효과의 이름과 값(effects.js).

