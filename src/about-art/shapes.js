// ---------- 작별(임시안) — 맞닿은 두 손끝이 천천히 떨어진다 ----------
//   다른 형상으로 바꿀 때는 이 칸(farewell)만 갈아 끼우면 된다 — fx 'part-ways' 는 handL · handR · spark 부분만 본다.

/** 왼쪽에서 뻗은 손(오른쪽 손은 좌우를 뒤집고, 팔이 위에서 내려온다) — 맞닿는 검지 끝(±4.4, 51)을 가운데로 K 배 */
const K = 1.75;
function hand(side) {
  const m = side === 'L' ? 1 : -1;
  const P = ([x, y]) => {
    const lift = side === 'R' ? -(Math.abs(x) - 4.4) * 0.24 : (Math.abs(x) - 4.4) * 0.06;
    return [x * m * K, 51 + (y + lift - 51) * K];
  };
  const R = (r) => r * K;
  const part = `hand${side}`;
  return [
    // 팔뚝 · 소매
    path(part, 0.5, [P([-66, 72]), P([-48, 63]), P([-31, 56])], R(4.6), R(3.6)),
    path(`cuff${side}`, 0.9, [P([-40.5, 60.4]), P([-37.5, 59.2])], R(4.7)),
    // 손등 · 접은 손가락 셋 · 엄지 · 뻗은 검지
    ell(part, 0.4, ...P([-24.5, 54]), R(6.4), R(4.4), -12 * m),
    path(part, 0.4, [P([-21, 56.4]), P([-16.6, 58]), P([-16, 61])], R(1.25), R(1)),
    path(part, 0.4, [P([-21.6, 58]), P([-18, 60.6]), P([-18, 63])], R(1.2), R(1)),
    path(part, 0.4, [P([-23, 59]), P([-20.6, 62.6])], R(1.1), R(0.95)),
    path(part, 0.4, [P([-25, 50.6]), P([-20.6, 48.4]), P([-17.4, 49.4])], R(1.25), R(1)),
    path(part, 0.4, [P([-19.6, 52.6]), P([-12, 51.4]), P([-4.4, 51])], R(1.3), R(1.05)),
  ];
}

