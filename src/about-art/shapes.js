//   남자는 고개를 숙여 여자를, 여자는 고개를 들어 남자를 본다.

const PX = 12.16; // 그림 1216px = 높이 100
const G = (x, y) => [(x - 416) / PX, y / PX];
const gell = (part, tone, x, y, rx, ry, rot = 0) => ell(part, tone, ...G(x, y), rx / PX, ry / PX, rot);
const gpath = (part, tone, pts, r, r2 = r) => path(part, tone, pts.map(([x, y]) => G(x, y)), r / PX, r2 / PX);
const gpoly = (part, tone, pts) => poly(part, tone, pts.map(([x, y]) => G(x, y)));

